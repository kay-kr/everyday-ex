/* ── 어떤 글에 어떤 동작이 나오는지 찾아 준다. 각 날 루틴이 이것으로 그날 동작만 추린다.
      이름이 직접 나온 것 + 묶음 이름으로 줄여 쓴 것을 함께 잡는다. ── */
window.DB_MOVES_FIND = function (texts) {
  const hay = (Array.isArray(texts) ? texts.join('  ') : String(texts));
  const want = new Set();
  for (const [bundle, members] of Object.entries(window.DB_MOVE_BUNDLES)) {
    if (hay.includes(bundle)) for (const n of members) want.add(n);
  }
  const hit = [];
  for (const m of window.DB_MOVES) {
    const names = [m.k].concat(m.alias || []);
    if (names.some(n => hay.includes(n)) || want.has(m.k)) hit.push(m);
  }
  return hit;
};

/* ── 하루 루틴에 딸려 나갈 "이 세션의 동작" 목록. plan.html 과 DASHBOARD.html 이 함께 쓴다.
      prefix 는 moves.html 까지의 상대 경로 ('' 또는 '_dashboard/'). ── */
/* 동작 카드의 id. moves.html 과 각 세션 링크가 같은 규칙을 쓴다.
   공백만 밑줄로 바꾼다 — 한글은 id 와 CSS 선택자 모두에서 그대로 쓸 수 있다. */
window.DB_MOVE_ID = function (m) { return 'm-' + String(m.k || m).replace(/\s+/g, '_'); };

window.DB_MOVES_PANEL = function (day, prefix) {
  const esc = s => String(s == null ? '' : s).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
  const texts = [day.theme].concat(day.blocks.map(b => b.name + ' ' + b.items.join(' ')));
  const hits = window.DB_MOVES_FIND(texts).filter(m => m.cat !== 'basic');
  if (!hits.length) return '';
  const href = m => (prefix || '') + 'moves.html#' + window.DB_MOVE_ID(m);
  const LABEL = { warm: '워밍업', run: '달리기', strength: '근력 · 무릎', ball: '볼 기술', cool: '쿨다운' };
  const groups = ['warm', 'run', 'strength', 'ball', 'cool']
    .map(c => [LABEL[c], hits.filter(m => m.cat === c)])
    .filter(g => g[1].length);
  return '<details class="movebox">' +
    '<summary>이 세션에 나오는 동작 ' + hits.length + '가지 — 하는 법 펼쳐 보기</summary>' +
    groups.map(([label, ms]) =>
      '<span class="movecat">' + label + ' <b>' + ms.length + '</b></span>' +
      '<ul class="movelist">' + ms.map(m =>
        '<li><a href="' + href(m) + '">' + esc(m.k) + '</a>' +
        (m.vol ? '<i>' + esc(m.vol) + '</i>' : '') +
        '<span>' + esc(m.tip) + '</span>' +
        (m.knee ? '<em>무릎 — ' + esc(m.knee) + '</em>' : '') + '</li>').join('') +
      '</ul>').join('') +
    '<p class="moveall"><a href="' + (prefix || '') + 'moves.html">동작 사전 전체 보기 →</a></p>' +
    '</details>';
};
