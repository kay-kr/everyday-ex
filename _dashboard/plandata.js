/* 한 세션의 총 시간은 블록 시간의 합이다. 요일마다 다르므로 손으로 적지 않고 여기서 계산한다.
   단, at:"home" 블록은 빼고 센다 — "운동장에서 얼마나 있어야 하는가"가 이 숫자의 쓸모이기 때문이다.
   집에서 하는 시간은 DB_HOME_MIN 으로 따로 센다. */
function DB_SUM_MIN(blocks) {
  return blocks.reduce(function (a, b) { return a + (b.min || 0); }, 0);
}
window.DB_DAY_MIN = function (day) {
  return DB_SUM_MIN(day.blocks.filter(function (b) { return b.at !== 'home'; }));
};
window.DB_HOME_MIN = function (day) {
  return DB_SUM_MIN(day.blocks.filter(function (b) { return b.at === 'home'; }));
};
window.DB_WEEK_MIN = function (no) {
  return window.DB_PLAN.days.filter(function (x) { return x.week === no; })
    .reduce(function (a, x) { return a + window.DB_DAY_MIN(x); }, 0);
};
window.DB_WEEK_HOME_MIN = function (no) {
  return window.DB_PLAN.days.filter(function (x) { return x.week === no; })
    .reduce(function (a, x) { return a + window.DB_HOME_MIN(x); }, 0);
};

/* 모든 페이지 머리말의 <time id="dbUpdated"> 를 위의 updated 값으로 채운다.
   페이지마다 날짜를 손으로 적으면 서로 어긋나므로 여기서 한 번에 처리한다. */
(function () {
  function fill() {
    var el = document.getElementById('dbUpdated');
    if (!el || !window.DB_PLAN) return;
    var v = window.DB_PLAN.updated;
    el.setAttribute('datetime', v);
    el.textContent = (window.DB && DB.kst) ? DB.kst(v) : v;
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', fill);
  else fill();
})();
