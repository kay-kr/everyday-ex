/* ── 시간 계산 ──
   세션의 총 시간은 블록 시간의 합이다. 손으로 적지 않고 여기서 계산한다. */
function DB_SUM_MIN(blocks) {
  return blocks.reduce(function (a, b) { return a + (b.min || 0); }, 0);
}
window.DB_FIELD_MIN = function (s) { return DB_SUM_MIN(s.blocks); };
window.DB_HOME_MIN = function (hw) { return DB_SUM_MIN(hw.blocks); };

/* 그 주의 운동장 세션들 · 집 루틴 */
window.DB_FIELD_OF = function (no) {
  return window.DB_PLAN.field.filter(function (x) { return x.week === no; });
};
window.DB_HOME_OF = function (no) {
  return window.DB_PLAN.home.weeks[Math.min(Math.max(no, 1), 3) - 1];
};
window.DB_WEEK_FIELD_MIN = function (no) {
  return window.DB_FIELD_OF(no).reduce(function (a, x) { return a + window.DB_FIELD_MIN(x); }, 0);
};
window.DB_WEEK_HOME_MIN = function (no) {
  return window.DB_HOME_MIN(window.DB_HOME_OF(no)) * 7;
};

/* ── 날짜 → 며칠째 · 몇 주차 ──
   집 루틴은 날짜가 있고 운동장 세션은 없다. 그래서 날짜 계산은 집 루틴 쪽에만 쓴다.
   start 하루 전까지는 0, 21일을 넘기면 22 이상이 나온다 — 부르는 쪽에서 판단한다. */
window.DB_DAY_NO = function (dateStr) {
  var a = new Date(window.DB_PLAN.start + 'T00:00+09:00').getTime();
  var b = new Date(dateStr + 'T00:00+09:00').getTime();
  return Math.round((b - a) / 86400000) + 1;
};
window.DB_WEEK_NO = function (dateStr) {
  var n = window.DB_DAY_NO(dateStr);
  if (n < 1) return 0;
  return Math.min(Math.ceil(n / 7), 4);
};
/* n일째 → "YYYY-MM-DD" */
window.DB_DATE_OF = function (n) {
  var a = new Date(window.DB_PLAN.start + 'T00:00+09:00').getTime() + (n - 1) * 86400000;
  return new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Seoul', year: 'numeric', month: '2-digit', day: '2-digit' }).format(new Date(a));
};
window.DB_DOW = function (dateStr) {
  return ['일', '월', '화', '수', '목', '금', '토'][new Date(dateStr + 'T00:00+09:00').getDay()];
};

/* 모든 페이지 머리말의 <time id="dbUpdated"> 를 위의 updated 값으로 채운다.
   페이지마다 날짜를 손으로 적으면 서로 어긋나므로 여기서 한 번에 처리한다. */
(function () {
  function fill() {
    var el = document.getElementById('dbUpdated');
    if (!el || !window.DB_PLAN) return;
    var v = window.DB_PLAN.updated;
    el.setAttribute('datetime', v);
    el.textContent = (window.DB && DB.kst) ? DB.kst(v) : v;
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', fill);
  else fill();
})();
